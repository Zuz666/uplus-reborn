"""Commit-only artifacts and explicit-input check receipts; no runtime dependencies."""

from __future__ import annotations

import argparse
import ast
import hashlib
import json
import os
import platform
import re
import shutil
import socket
import stat
import subprocess
import sys
import tarfile
import tempfile
import time
import zlib
from contextlib import contextmanager
from datetime import UTC, datetime
from pathlib import Path

PACKAGE = "custom_components/uplus_reborn"
HEX256 = re.compile(r"[0-9a-f]{64}\Z")
COMMIT = re.compile(r"[0-9a-f]{40}\Z")
DOCKER_TARGETS = ("test", "core-current")
DOCKER_UNAVAILABLE_EXIT = 2
EXCLUDED = frozenset({
    ".git", ".local", ".venv", "venv", "node_modules", "__pycache__",
    ".pytest_cache", ".ruff_cache", ".mypy_cache", ".cache", "build", "dist",
    "raw", "captures", "decompiled", "secrets",
})


def _no_links(path: Path) -> None:
    """Reject links/junctions, including ancestors, before following a path."""
    for part in (path, *path.parents):
        if part.is_symlink() or part.is_junction():
            raise ValueError(f"Links are not allowed: {part}")


def _sha(path: Path) -> str:
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def _pairs(pairs: list[tuple[str, object]]) -> dict:
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"Duplicate JSON key: {key}")
        result[key] = value
    return result


def _json(path: Path) -> dict:
    value = json.loads(path.read_text(encoding="utf-8"), object_pairs_hook=_pairs)
    if not isinstance(value, dict):
        raise TypeError(f"Expected a JSON object: {path}")
    return value


def _write_json(path: Path, value: dict) -> None:
    _no_links(path.absolute())
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as stream:
            json.dump(value, stream, indent=2, sort_keys=True)
            stream.write("\n")
        os.replace(temporary, path)
    finally:
        Path(temporary).unlink(missing_ok=True)


def _member_name(name: str, *, directory: bool = False) -> str:
    if directory and name.endswith("/"):
        name = name[:-1]
    parts = name.split("/")
    if not name or any(
        not part or part in {".", ".."} or part.endswith((".", " "))
        or any(ord(char) < 32 or char in '\\:<>"|?*' for char in part)
        or re.fullmatch(r"(?i)(CON|PRN|AUX|NUL|COM[1-9]|LPT[1-9])(?:\..*)?", part)
        for part in parts
    ):
        raise ValueError(f"Unsafe member path: {name!r}")
    if not (name.startswith(PACKAGE + "/") or directory and name in {
        "custom_components", PACKAGE,
    }):
        raise ValueError(f"Member outside package: {name}")
    if "__pycache__" in parts or name.endswith(".pyc"):
        raise ValueError(f"Generated bytecode in artifact: {name}")
    return name


def _manifest(bundle: Path) -> dict:
    for path in (bundle, bundle / "artifact.json", bundle / "artifact.tar.gz"):
        _no_links(path.absolute())
    result = _json(bundle / "artifact.json")
    if set(result) != {"schema", "commit", "archive_sha256", "files"}:
        raise ValueError("Unexpected artifact manifest fields")
    if type(result["schema"]) is not int or result["schema"] != 1:
        raise ValueError("Unsupported artifact schema")
    if not isinstance(result["commit"], str) or not COMMIT.fullmatch(result["commit"]):
        raise ValueError("Invalid artifact commit")
    if not isinstance(result["archive_sha256"], str) or not HEX256.fullmatch(result["archive_sha256"]):
        raise ValueError("Invalid archive hash")
    files = result["files"]
    if not isinstance(files, dict) or not files:
        raise ValueError("Artifact must contain package files")
    for name, digest in files.items():
        _member_name(name)
        if not isinstance(digest, str) or not HEX256.fullmatch(digest):
            raise ValueError(f"Invalid file hash: {name}")
    return result


def _archive_files(archive: tarfile.TarFile) -> dict[str, str]:
    files = {}
    names = {}
    directories = set()
    spellings = {}
    for member in archive.getmembers():
        if not (member.isdir() or member.isreg()) or member.issparse():
            raise ValueError(f"Non-regular archive member: {member.name}")
        name = _member_name(member.name, directory=member.isdir())
        for component in (Path(name), *Path(name).parents):
            spelling = component.as_posix()
            prior = spellings.setdefault(spelling.casefold(), spelling)
            if prior != spelling:
                raise ValueError(f"Case-colliding archive path: {name}")
        folded = name.casefold()
        if folded in names:
            raise ValueError(f"Duplicate/case-colliding archive member: {name}")
        names[folded] = name
        if member.isdir():
            directories.add(name)
            continue
        stream = archive.extractfile(member)
        if stream is None:
            raise ValueError(f"Unreadable archive member: {name}")
        with stream:
            files[name] = hashlib.file_digest(stream, "sha256").hexdigest()
    for name in names.values():
        for parent in Path(name).parents:
            if parent.as_posix().casefold() in names:
                actual = names[parent.as_posix().casefold()]
                if actual not in directories or actual != parent.as_posix():
                    raise ValueError(f"Conflicting archive path: {name}")
    if not files:
        raise ValueError("Archive contains no package files")
    return files


@contextmanager
def _validated(bundle: Path):
    manifest = _manifest(bundle)
    try:
        # Validate and extract through the same open descriptor, not a reopened path.
        with (bundle / "artifact.tar.gz").open("rb") as source:
            if hashlib.file_digest(source, "sha256").hexdigest() != manifest["archive_sha256"]:
                raise ValueError("Archive SHA-256 mismatch")
            source.seek(0)
            with tarfile.open(fileobj=source, mode="r:gz") as archive:
                if _archive_files(archive) != manifest["files"]:
                    raise ValueError("Archive member set or file hashes differ from manifest")
                yield manifest, archive
    except (tarfile.TarError, EOFError, zlib.error) as error:
        raise ValueError(f"Invalid artifact archive: {error}") from error


def load_artifact(bundle: Path) -> dict:
    """Validate archive hash, every member and its bytes; return schema-1 manifest."""
    with _validated(Path(bundle)) as (manifest, _):
        return manifest


def extract_artifact(bundle: Path, destination: Path) -> dict:
    """Validate before writing; extract regular files only into a fresh/empty root."""
    destination = Path(destination).absolute()
    _no_links(destination)
    if destination.exists() and (not destination.is_dir() or any(destination.iterdir())):
        raise ValueError("Extraction destination must be a fresh or empty directory")
    with _validated(Path(bundle)) as (manifest, archive):
        destination.mkdir(parents=True, exist_ok=True)
        for member in archive.getmembers():
            name = _member_name(member.name, directory=member.isdir())
            target = destination / name
            _no_links(target)
            if member.isdir():
                target.mkdir(parents=True, exist_ok=True)
            else:
                target.parent.mkdir(parents=True, exist_ok=True)
                with archive.extractfile(member) as source, target.open("xb") as output:
                    shutil.copyfileobj(source, output)
        return manifest


def verify_installed(manifest: dict, installed: Path) -> None:
    """Compare the complete installed package; only generated Python cache may differ."""
    root = Path(installed).absolute() / PACKAGE
    _no_links(root)
    if not root.is_dir():
        raise ValueError("Installed package directory is missing")
    files = {}
    for directory, dirs, names in os.walk(root, followlinks=False):
        for name in dirs + names:
            path = Path(directory) / name
            _no_links(path)
            mode = path.stat().st_mode
            if not (stat.S_ISDIR(mode) or stat.S_ISREG(mode)):
                raise ValueError(f"Non-regular installed member: {path}")
        # Visit caches too: a link inside an ignored cache must not escape validation.
        for name in names:
            path = Path(directory) / name
            relative = path.relative_to(Path(installed).absolute()).as_posix()
            if "__pycache__" in path.relative_to(root).parts or name.endswith(".pyc"):
                continue
            files[relative] = _sha(path)
    if files != manifest["files"]:
        raise ValueError("Installed package member set or hashes differ from artifact")


def _git(repo: Path, *args: str) -> bytes:
    result = subprocess.run(
        ["git", "-c", "core.autocrlf=false", "-c", "core.eol=lf", "-C", str(repo), *args],
        capture_output=True, check=False,
    )
    if result.returncode:
        raise ValueError(f"git {args[0]} failed: {result.stderr.decode('utf-8', 'replace').strip()}")
    return result.stdout


def build_artifact(repo: Path, commit: str, output: Path) -> dict:
    """Archive one resolved commit, rejecting attribute-driven omissions/substitution."""
    resolved = _git(repo, "rev-parse", "--verify", "--end-of-options", commit + "^{commit}").decode().strip()
    if not COMMIT.fullmatch(resolved):
        raise ValueError("Expected a SHA-1 Git commit")
    entries = _git(repo, "ls-tree", "-rz", resolved, "--", PACKAGE)
    expected = {}
    for entry in entries.split(b"\0"):
        if not entry:
            continue
        header, raw_name = entry.split(b"\t", 1)
        mode, kind, object_id = header.split()
        name = raw_name.decode("utf-8")
        _member_name(name)
        if mode not in {b"100644", b"100755"} or kind != b"blob":
            raise ValueError(f"Commit contains a non-regular package member: {name}")
        expected[name] = hashlib.sha256(_git(repo, "cat-file", "blob", object_id.decode())).hexdigest()
    if not expected:
        raise ValueError("Commit contains no package files")
    output = Path(output).absolute()
    _no_links(output)
    output.mkdir(parents=True, exist_ok=False)
    try:
        archive = output / "artifact.tar.gz"
        _git(repo, "archive", "--format=tar.gz", f"--output={archive}", resolved, "--", PACKAGE)
        manifest = {
            "schema": 1, "commit": resolved, "archive_sha256": _sha(archive),
            "files": dict(sorted(expected.items())),
        }
        _write_json(output / "artifact.json", manifest)
        return load_artifact(output)
    except BaseException:
        shutil.rmtree(output)
        raise


def _input_hashes(paths: list[Path]) -> dict:
    """Selection is explicit; exclusions apply only below a selected directory."""
    result = {}

    def visit(path: Path, relative: str, entries: dict, *, explicit: bool = False) -> None:
        _no_links(path)
        if not explicit and (path.name in EXCLUDED or path.suffix == ".pyc"):
            return
        mode = path.stat().st_mode
        if stat.S_ISREG(mode):
            entries[relative] = {"kind": "file", "sha256": _sha(path)}
        elif stat.S_ISDIR(mode):
            entries[relative] = {"kind": "directory"}
            for child in sorted(path.iterdir()):
                visit(child, child.name if relative == "." else relative + "/" + child.name, entries)
        else:
            raise ValueError(f"Non-regular input: {path}")

    for selected in paths:
        selected = selected.absolute()
        _no_links(selected)
        if not selected.exists():
            raise ValueError(f"Input does not exist: {selected}")
        entries = {}
        visit(selected, ".", entries, explicit=True)
        result[str(selected)] = entries
    return result


def _runtime() -> dict:
    return {
        "python": sys.version, "executable": sys.executable,
        "implementation": platform.python_implementation(), "os": platform.platform(),
        "delivery_sha256": _sha(Path(__file__)),
    }


def _emit_output(stdout: str, stderr: str) -> None:
    # Child CRLF is already present; avoid a second Windows newline translation.
    for stream, text in ((sys.stdout, stdout), (sys.stderr, stderr)):
        stream.flush()
        if hasattr(stream, "buffer"):
            stream.buffer.write(text.encode("utf-8"))
            stream.buffer.flush()
        else:
            stream.write(text)


def run_check(record: Path, inputs: list[Path], context: dict[str, str], command: list[str]) -> int:
    """Reuse only a completed success for identical declared inputs and execution context.

    Callers own dependency selection and tool/environment version context. The command
    is executed exactly once without a shell; this is not dependency discovery.
    """
    if not command or not inputs:
        raise ValueError("Check requires a command and at least one input")
    _no_links(record.absolute())
    binding = {
        "command": command, "cwd": str(Path.cwd()), "inputs": _input_hashes(inputs),
        "context": context, "runtime": _runtime(),
    }
    try:
        previous = _json(record)
    except (OSError, ValueError, TypeError):
        previous = {}
    if (previous.get("schema") == 1 and previous.get("binding") == binding
            and previous.get("status") == "completed" and previous.get("returncode") == 0
            and previous.get("inputs_stable") is True
            and isinstance(previous.get("stdout"), str) and isinstance(previous.get("stderr"), str)):
        print(f"Reusing successful check: {record}", file=sys.stderr)
        _emit_output(previous["stdout"], previous["stderr"])
        return 0
    receipt = {
        "schema": 1, "binding": binding, "status": "running",
        "started_at": datetime.now(UTC).isoformat(),
    }
    # Invalidate old success before dispatch, including when the process is interrupted.
    _write_json(record, receipt)
    started = time.monotonic()
    try:
        result = subprocess.run(command, capture_output=True, check=False, shell=False)
        returncode = result.returncode
        stdout, stderr = result.stdout.decode("utf-8", "replace"), result.stderr.decode("utf-8", "replace")
    except OSError as error:
        returncode, stdout, stderr = 127, "", str(error) + "\n"
    try:
        stable = _input_hashes(inputs) == binding["inputs"]
    except (ValueError, OSError):
        stable = False
    receipt.update({
        "status": "completed", "finished_at": datetime.now(UTC).isoformat(),
        "duration_seconds": time.monotonic() - started, "returncode": returncode,
        "stdout": stdout, "stderr": stderr, "inputs_stable": stable,
    })
    _write_json(record, receipt)
    _emit_output(stdout, stderr)
    return returncode if returncode >= 0 else 128 - returncode


def smoke_bootstrap_components(repo: Path) -> tuple[str, ...]:
    """Extract BOOTSTRAP_COMPONENTS from tools/ha_smoke.py without importing Home Assistant."""
    path = repo / "tools/ha_smoke.py"
    _no_links(path.absolute())
    if not path.is_file():
        raise ValueError("Missing Docker recipe input: tools/ha_smoke.py")
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    constants: dict[str, tuple[str, ...]] = {}
    for node in tree.body:
        if not isinstance(node, ast.Assign) or len(node.targets) != 1 or not isinstance(node.targets[0], ast.Name):
            continue
        name = node.targets[0].id
        if name not in {"CORE_COMPONENTS", "BOOTSTRAP_COMPONENTS"} or not isinstance(node.value, (ast.Tuple, ast.List)):
            continue
        items: list[str] = []
        for elt in node.value.elts:
            if isinstance(elt, ast.Constant) and isinstance(elt.value, str):
                items.append(elt.value)
            elif isinstance(elt, ast.Starred) and isinstance(elt.value, ast.Name) and elt.value.id in constants:
                items.extend(constants[elt.value.id])
            else:
                raise ValueError(f"Unsupported element in {name} of tools/ha_smoke.py")
        constants[name] = tuple(items)
    components = constants.get("BOOTSTRAP_COMPONENTS") or constants.get("CORE_COMPONENTS")
    if not components or any(not re.fullmatch(r"[a-z0-9_]+", item) for item in components):
        raise ValueError("Missing valid BOOTSTRAP_COMPONENTS in tools/ha_smoke.py")
    return components


def docker_image_tag(repo: Path, target: str) -> str:
    """Compute a deterministic image tag from the Docker recipe, lockfiles, and smoke components."""
    if target not in DOCKER_TARGETS:
        raise ValueError(f"Unsupported Docker target: {target}")
    components = smoke_bootstrap_components(repo)
    digest = hashlib.sha256(f"target={target}\n".encode())
    for rel in ("tools/Dockerfile", "pyproject.toml", "uv.lock"):
        path = repo / rel
        _no_links(path.absolute())
        if not path.is_file():
            raise ValueError(f"Missing Docker recipe input: {rel}")
        digest.update(f"{rel}:{_sha(path)}\n".encode())
    if target == "test":
        digest.update(f"smoke_components:{' '.join(components)}\n".encode())
    return f"uplus-reborn-{target}:{digest.hexdigest()[:12]}"


def require_docker(docker_bin: str = "docker") -> str:
    """Fail fast when the Docker CLI or daemon is unavailable; never fall back to WSL."""
    try:
        probe = subprocess.run(
            [docker_bin, "version", "--format", "{{.Server.Version}}"],
            capture_output=True, text=True, encoding="utf-8", errors="replace",
            timeout=15, check=False, shell=False,
        )
    except (OSError, subprocess.TimeoutExpired) as error:
        raise RuntimeError(
            "DOCKER_UNAVAILABLE: Docker daemon is unavailable; stop workflow and notify the user "
            f"({error})"
        ) from error
    version = probe.stdout.strip()
    if probe.returncode != 0 or not version:
        detail = (probe.stderr or probe.stdout).strip().splitlines()
        reason = detail[-1] if detail else f"exit {probe.returncode}"
        raise RuntimeError(
            "DOCKER_UNAVAILABLE: Docker daemon is unavailable; stop workflow and notify the user "
            f"({reason})"
        )
    return version


def ensure_docker_image(repo: Path, target: str, *, docker_bin: str = "docker") -> dict[str, str]:
    """Reuse an existing content-addressed test image or build it once."""
    server_version = require_docker(docker_bin)
    components = " ".join(smoke_bootstrap_components(repo))
    tag = docker_image_tag(repo, target)
    inspect = subprocess.run(
        [docker_bin, "image", "inspect", "--format", "{{.Id}}", tag],
        capture_output=True, text=True, encoding="utf-8", errors="replace",
        check=False, shell=False,
    )
    if inspect.returncode == 0 and inspect.stdout.strip():
        return {
            "built": "false", "image": tag, "image_id": inspect.stdout.strip(),
            "server_version": server_version, "target": target,
        }
    build = subprocess.run(
        [
            docker_bin, "build", "--target", target,
            "--build-arg", f"SMOKE_COMPONENTS={components}",
            "-t", tag, "-f", str(repo / "tools/Dockerfile"), str(repo),
        ],
        capture_output=True, text=True, encoding="utf-8", errors="replace",
        check=False, shell=False,
    )
    if build.returncode != 0:
        detail = (build.stderr or build.stdout).strip()
        raise ValueError(f"Docker image build failed for {target}: {detail}")
    after = subprocess.run(
        [docker_bin, "image", "inspect", "--format", "{{.Id}}", tag],
        capture_output=True, text=True, encoding="utf-8", errors="replace",
        check=False, shell=False,
    )
    if after.returncode != 0 or not after.stdout.strip():
        raise ValueError(f"Built Docker image could not be inspected: {tag}")
    return {
        "built": "true", "image": tag, "image_id": after.stdout.strip(),
        "server_version": server_version, "target": target,
    }


def _parse_context(items: list[str]) -> dict[str, str]:
    context = {}
    for item in items:
        key, separator, value = item.partition("=")
        if not key or not separator or key in context:
            raise ValueError("Context must use unique, nonempty KEY=VALUE keys")
        context[key] = value
    return context


def run_docker(
    repo: Path,
    target: str,
    command: list[str],
    *,
    record: Path | None = None,
    inputs: list[Path] | None = None,
    context: dict[str, str] | None = None,
    docker_bin: str = "docker",
) -> int:
    """Run a command in a reproducible offline Docker container after preflight."""
    _no_links(repo.absolute())
    info = ensure_docker_image(repo, target, docker_bin=docker_bin)
    if not command:
        print(json.dumps(info, indent=2, sort_keys=True))
        return 0
    if command[0].endswith(".py"):
        command = ["python3", *command]
    serving = "--serve" in command
    if serving:
        if record is not None:
            raise ValueError("--serve cannot be cached with --record")
        with socket.socket() as reservation:
            reservation.bind(("127.0.0.1", 0))
            port = reservation.getsockname()[1]
        docker_cmd = [
            docker_bin, "run", "--rm", "--init", "-i",
            "-p", f"127.0.0.1:{port}:{port}",
            "-e", f"UPLUS_SMOKE_CONTAINER_SERVE_PORT={port}",
            "-v", f"{repo.resolve()}:/workspace", "-w", "/workspace",
            info["image"], *command,
        ]
    else:
        docker_cmd = [
            docker_bin, "run", "--rm", "--init",
            *([] if record is not None else ["-i"]),
            "--network", "none",
            "-v", f"{repo.resolve()}:/workspace", "-w", "/workspace",
            info["image"], *command,
        ]
    if record is not None:
        if not inputs:
            raise ValueError("--record requires at least one --input")
        merged_context = {
            **(context or {}),
            "docker_target": target,
            "docker_image": info["image"],
            "docker_image_id": info["image_id"],
        }
        return run_check(record, inputs, merged_context, docker_cmd)
    completed = subprocess.run(docker_cmd, check=False, shell=False)
    return completed.returncode if completed.returncode >= 0 else 128 - completed.returncode


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="action", required=True)
    build = commands.add_parser("build", help="Build from committed package bytes, never working-tree files")
    build.add_argument("--commit", required=True)
    build.add_argument("--output", type=Path, required=True)
    build.add_argument("--repo", type=Path, default=Path.cwd())
    verify = commands.add_parser("verify", help="Validate the bundle and optionally an installed package")
    verify.add_argument("--bundle", type=Path, required=True)
    verify.add_argument("--installed", type=Path)
    check = commands.add_parser("check", help="Run/reuse a check for explicit inputs and caller-supplied version context")
    check.add_argument("--record", type=Path, required=True)
    check.add_argument("--input", type=Path, action="append", required=True)
    check.add_argument("--context", action="append", default=[], metavar="KEY=VALUE")
    check.add_argument("command", nargs=argparse.REMAINDER)
    docker = commands.add_parser("docker", help="Verify Docker availability, build test image once if absent, and run inside container")
    docker.add_argument("--target", choices=DOCKER_TARGETS, default="test")
    docker.add_argument("--repo", type=Path, default=Path.cwd())
    docker.add_argument("--docker-bin", default=os.environ.get("UPLUS_DOCKER_BIN", "docker"))
    docker.add_argument("--record", type=Path)
    docker.add_argument("--input", type=Path, action="append", default=[])
    docker.add_argument("--context", action="append", default=[], metavar="KEY=VALUE")
    docker.add_argument("command", nargs=argparse.REMAINDER)
    args = parser.parse_args(argv)
    try:
        if args.action == "build":
            manifest = build_artifact(args.repo, args.commit, args.output)
        elif args.action == "verify":
            manifest = load_artifact(args.bundle)
            if args.installed is not None:
                verify_installed(manifest, args.installed)
        elif args.action == "check":
            context = _parse_context(args.context)
            command = args.command[1:] if args.command and args.command[0] == "--" else args.command
            return run_check(args.record, args.input, context, command)
        else:
            context = _parse_context(args.context)
            command = args.command[1:] if args.command and args.command[0] == "--" else args.command
            return run_docker(
                args.repo, args.target, command,
                record=args.record, inputs=args.input, context=context,
                docker_bin=args.docker_bin,
            )
        print(json.dumps(manifest, indent=2, sort_keys=True))
        return 0
    except RuntimeError as error:
        print(f"delivery: {error}", file=sys.stderr)
        return DOCKER_UNAVAILABLE_EXIT
    except (ValueError, TypeError, OSError) as error:
        print(f"delivery: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
